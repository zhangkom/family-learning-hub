import { createRequire } from 'node:module';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const connectionPath = process.env.FAMILY_DEV_CONNECTION_PATH;
if (!connectionPath) throw new Error('A private synthetic setup connection file is required');
const config = JSON.parse(readFileSync(connectionPath, 'utf8'));
assert.equal(config.syntheticOnly, true);
assert.equal(config.aiEnabled, false);
assert.equal(new URL(config.apiBase).hostname, '127.0.0.1');
assert.equal(typeof config.setupToken, 'string');
assert.ok(config.setupToken.length >= 32);
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const client = process.env.CLIENT_URL || 'http://127.0.0.1:3178';
assert.equal(new URL(client).hostname, '127.0.0.1');
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
let stage = 'check empty synthetic environment';
try {
  const response = await fetch(`${config.apiBase}/setup`);
  assert.equal(response.status, 200);
  assert.deepEqual(await response.json(), { enabled: true, needsSetup: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  let extraLoginRequests = 0;
  page.on('request', (request) => { if (request.url() === `${config.apiBase}/session/login`) extraLoginRequests++; });
  stage = 'open native-style registration form';
  await page.goto(client);
  await page.getByLabel('家庭服务地址').fill(config.apiBase);
  await page.getByRole('tab', { name: '首次注册家庭账号' }).click();
  await page.getByLabel('家庭启用码', { exact: true }).fill(config.setupToken);
  await page.getByLabel('家庭账号', { exact: true }).fill(config.username);
  await page.getByLabel('密码', { exact: true }).fill(config.password);
  await page.getByLabel('确认密码', { exact: true }).fill(config.password);
  stage = 'register and directly sign in';
  const setupResponse = page.waitForResponse((r) => r.url() === `${config.apiBase}/session/setup` && r.request().method() === 'POST');
  await page.getByRole('button', { name: '注册并进入家庭学习', exact: true }).click();
  const registered = await setupResponse;
  assert.equal(registered.status(), 200);
  assert.equal((await registered.allHeaders())['set-cookie'], undefined);
  await page.getByRole('navigation', { name: '主要页面' }).waitFor();
  assert.equal(extraLoginRequests, 0);
  const settings = await page.evaluate(() => JSON.stringify(localStorage));
  assert.equal(settings.includes(config.setupToken), false);
  assert.equal(settings.includes(config.password), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const closed = await fetch(`${config.apiBase}/setup`);
  assert.deepEqual(await closed.json(), { enabled: true, needsSetup: false });
  await page.close();
  stage = 'closed registration and subsequent ordinary login';
  const returning = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await returning.goto(client);
  await returning.getByLabel('家庭服务地址').fill(config.apiBase);
  await returning.getByRole('tab', { name: '首次注册家庭账号' }).click();
  await returning.getByText('当前家庭注册入口已关闭。已有家庭成员请使用家长创建的账号登录；新增家庭需由管理员开通。', { exact: true }).waitFor();
  assert.equal(await returning.getByRole('button', { name: '注册并进入家庭学习', exact: true }).isDisabled(), true);
  await returning.getByRole('tab', { name: '已有账号登录' }).click();
  await returning.getByLabel('家庭账号', { exact: true }).fill(config.username);
  await returning.getByLabel('密码', { exact: true }).fill(config.password);
  await returning.getByRole('button', { name: '进入家庭学习', exact: true }).click();
  await returning.getByRole('navigation', { name: '主要页面' }).waitFor();
  mkdirSync('test-results', { recursive: true });
  const report = { passed: true, syntheticOnly: true, aiEnabled: false, productionWrites: 0, checkedAt: new Date().toISOString(), checks: ['empty-family status', 'registration from client', 'direct Bearer login without cookie or second login', 'setup code and password absent from local settings', 'registration closes after first family', 'new ordinary login succeeds', 'mobile layout'] };
  writeFileSync('test-results/registration-integration-result.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} catch (error) {
  let details = error instanceof Error ? error.message : 'Unknown failure';
  for (const secret of [config.setupToken, config.password, config.username]) if (secret) details = details.replaceAll(secret, '[redacted]');
  console.error(`Synthetic registration integration failed during ${stage}: ${details}`);
  process.exitCode = 1;
} finally { await browser.close(); }
